// Wie FTmake in Vim: Name, sonst die erste Zeile, die eine Art verraet; sonst GNU
function make(base, lines) {
  if (base === 'BSDmakefile') return 'make-bsd';
  if (base === 'GNUmakefile' || !/[mM]akefile|\.(?:mk|mak)$/.test(base)) return 'make';
  for (const line of lines.slice(0, 999)) {
    if (/^\s*!\s*(?:ifn?(?:def)?|include|message|error)(?![A-Za-z0-9_])/i.test(line)) return 'make-microsoft';
    if (/^\.(?:export|error|for|if(?:n?(?:def|make))?|info|warning)(?![A-Za-z0-9_])/.test(line)) return 'make-bsd';
    if (/^ *(?:ifn?(?:eq|def)|define|override)(?![A-Za-z0-9_])|\$[({][a-z-]+\s+\S+/.test(line)) return 'make';
  }
  return 'make';
}

// diff.vim unterscheidet "unified" von den anderen Formaten
const diff = (lines) => (lines.some((line) => /^@@ -\S+ \+\S+ @@/.test(line)) ? 'diff' : 'diff-context');

// Name der Regeln in syntaxdaten
function typeFor(fileName, text, ignoreCase = IGNORE_CASE) {
  const type = fileType(fileName, text, ignoreCase);
  const base = () => fileName.split(/[/\\]/).pop();
  if (type === 'sh') return shell(base(), text.split(/\r?\n/, 1)[0]);
  if (type === 'make') return make(base(), text.split(/\r?\n/));
  if (type === 'diff') return diff(text.split(/\r?\n/));
  // Wie tex.vim: In Stildateien gehoert "@" zu den Befehlsnamen
  if (type === 'tex') return /\.dtx$/.test(base()) ? 'tex-dtx' : /\.(?:sty|cls|clo|ltx)$/.test(base()) ? 'tex-sty' : 'tex';
  return type;
}

// Dateityp wie in Vim
function fileType(fileName, text, ignoreCase) {
  let base = fileName.split(/[/\\]/).pop();
  while (COPY.test(base) && base.replace(COPY, '')) base = base.replace(COPY, '');
  if (base.endsWith('.in') && base !== 'configure.in' && base.length > 3) base = base.slice(0, -3);

  let lines = null;
  const content = () => (lines ||= text.split(/\r?\n/));

  const full = fileName.replace(/\\/g, '/');
  const byPath = PATHS.find(([pattern]) => pattern.test(full));
  if (byPath) return byPath[1];

  const name = own(table.namen, base);
  if (name) return name;

  const dot = base.lastIndexOf('.');
  let extension = dot > 0 ? base.slice(dot + 1) : base.startsWith('.') ? base.slice(1) : '';
  // Zwei Punkte: "x.ml.cppo", "x.app.src"
  const two = /[^.]\.([^.]+\.[^.]+)$/.exec(base)?.[1];
  if (two && own(table.endungen, two)) return table.endungen[two];
  if (ignoreCase) {
    // ".C" und ".H" sind dann nicht C++
    if (extension === 'C') return 'c';
    if (extension === 'H') extension = 'h';
  }
  const lower = extension.toLowerCase();
  const key = own(BY_CONTENT, extension) || own(table.endungen, extension) ? extension
    : ignoreCase ? lower : extension;
  const decide = own(BY_CONTENT, key);
  if (decide) return decide(content(), full);
  const type = own(table.endungen, key);
  // Bei HTML-Vorlagen (Angular, Django) faerbt Vim zusaetzlich; hier gelten die HTML-Regeln
  if (type) return type;
  if (ignoreCase) {
    const folded = Object.keys(table.namen).find((n) => n.toLowerCase() === base.toLowerCase());
    if (folded) return table.namen[folded];
  }
  // *akefile und Namensanfaenge wie "Dockerfile.dev". Wie in Vim erst, wenn Name und Endung
  // fuer keinen anderen Typ stehen ("Makefile.am", "Dockerfile.vim")
  if (table.fremd.namen.includes(base) || table.fremd.endungen.includes(key)) {
    return text && content()[0].startsWith('#!') ? shebang(content()) : null;
  }
  if (/[mM]akefile$/.test(base)) return 'make';
  const prefix = !IGNORED.test(base) && PREFIXES.find(([pattern]) => pattern.test(base));
  if (prefix) return prefix[1];
  if (!text) return null;
  const lines2 = content();
  if (lines2[0].startsWith('#!')) return shebang(lines2);
  return dot > 0 ? null : plain(lines2);
}

