// Welche Syntaxregeln gelten fuer eine Datei? Wie in Vim entscheidet der Dateiname
// (dateitypen.json), bei mehrdeutigen Endungen der Inhalt (nachgebildet nach Vims
// filetype.vim, autoload/dist/ft.vim und script.vim).
// null = Vim wuerde einen Typ waehlen, fuer den es hier keine Regeln gibt, oder keinen.
'use strict';
