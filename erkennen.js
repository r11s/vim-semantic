// Unter Windows und macOS beachtet Vim die Gross-/Kleinschreibung von Dateinamen nicht
const IGNORE_CASE = process.platform === 'win32' || process.platform === 'darwin';

// Angehaengte Endungen von Sicherungen u. ae.: Vim sieht auf den Namen davor
const COPY = /(?:~+|\.(?:orig|bak|old|new|dpkg-dist|dpkg-old|dpkg-new|dpkg-bak|rpmsave|rpmnew|pacsave|pacnew))$/;

const own = (object, key) => (Object.prototype.hasOwnProperty.call(object, key) ? object[key] : undefined);

// ---- Entscheidungen nach dem Inhalt ----------------------------------------------

const firstNonBlank = (lines) => lines.find((line) => /\S/.test(line)) ?? '';
const any = (lines, count, pattern) => lines.slice(0, count).some((line) => pattern.test(line));

const PASCAL_COMMENT = /^\s*(?:\{|\(\*|\/\/)/;
const PASCAL_KEYWORD = /^\s*(?:program|unit|library|uses|begin|procedure|function|const|type|var)(?!\w)/i;
const isPascal = (line) => PASCAL_COMMENT.test(line) || PASCAL_KEYWORD.test(line);

// ".h": Objective-C, sonst C++, sonst C
function header(lines) {
  for (const line of lines.slice(0, 99)) {
    if (/^[ \t]*@(?:class|interface|end)(?![\p{L}\p{N}_])/u.test(line)) return null;
    if (/^[ \t]*(?:class|namespace|template|using)(?![\p{L}\p{N}_])/u.test(line)) return 'cpp';
  }
  return 'c';
}

// ".m": Objective-C oder MATLAB (Octave, Mathematica, Murphi haben keine Regeln)
function dotM(lines) {
  let comment = false;
  for (const line of lines.slice(0, 99)) {
    if (/^\s*\/\*/.test(line)) comment = true;
    if (/^\s*\/\/|^\s*@import(?!\w)|^\s*#\s*(?:import|include|define|if|ifn?def|undef|line|error|pragma)(?!\w)/.test(line)) return 'objc';
    if (/^\s*(?:#|%!)|^\s*unwind_protect(?!\w)|(?:^|;)\s*end(?:_try_catch|classdef|enumeration|events|methods|parfor|properties)(?!\w)/.test(line)) return null;
    if (/^\s*%/.test(line)) return 'matlab';
    if (/^\s*\(\*/.test(line)) return null;
    if (/^\s*(?:(?:type|var)(?!\w)|--)/i.test(line)) return null;
  }
  return comment ? 'objc' : 'matlab';
}

const perlOrProlog = (lines) => {
  const line = firstNonBlank(lines);
  return /(?<!\w)prolog(?!\w)/.test(line) || /^\s*(?::-|%+(?:\s|$)|\/\*)|\.\s*$/.test(line) ? 'prolog' : 'perl';
};

// ".v": Verilog (Coq und die Sprache V haben keine Regeln)
function dotV(lines) {
  let comment = false;
  for (const line of lines.slice(0, 500)) {
    if (/^\s*\/\*/.test(line)) comment = true;
    if (comment) {
      if (line.includes('*/')) comment = false;
      continue;
    }
    if (/^\s*\/\//.test(line)) continue;
    if ((/\.\s*$/.test(line) && !/\/[/*]/.test(line)) || (line.includes('(*') && !/\/[/*].*\(\*/.test(line))) return null;
    if (/;\s*(?:\/[/*].*)?$|^\s*module\s+\w+\s*\(/.test(line)) return 'verilog';
  }
  return null;
}

// ".bas": Visual Basic oder BASIC (FreeBASIC und QB64 haben keine Regeln)
function dotBas(lines) {
  for (const line of lines.slice(0, 100)) {
    if (/^\s*(?:Attribute\s+VB_Name|Begin\s+(?:VB\.|\{(?:[0-9A-F]+-)+[0-9A-F]+\}))/i.test(line)) return 'vb';
    if (/^\s*(?:#\s*[a-z]+|option\s+(?:byval|dynamic|escape|(?:no)?gosub|nokeyword|private|static)(?!\w)|(?:'|rem)\s*\$lang(?!\w)|def(?:byte|longint|short|ubyte|uint|ulongint|ushort)(?!\w))/i.test(line) ||
        /^\s*\/'/.test(line) ||
        /^\s*(?:extern|var|enum|private|scope|union|byref|operator|constructor|delete|namespace|public|property|with|destructor|using)(?!\w)(?!\s*[:=(])/i.test(line)) return null;
    if (/^\s*(?:\$[a-z]+|option\s+(?:_explicit|_?explicitarray)(?!\w))/i.test(line)) return null;
  }
  return 'basic';
}

// ".p": Pascal oder Progress
function dotP(lines) {
  for (let i = 0; i < 10 && i < lines.length - 1; i++) {
    if (isPascal(lines[i])) return 'pascal';
    if (!/^\s*$/.test(lines[i]) || lines[i].startsWith('/*')) break;
  }
  return 'progress';
}

// asm-Datei: andere Assembler-Arten haben keine Regeln
function assembler(lines) {
  const mode = /\sasmsyntax=([a-zA-Z0-9]+)\s/.exec(` ${lines.slice(0, 5).join(' ')} `);
  if (mode) return mode[1] === 'asm' ? 'asm' : null;
  let comment = false;
  for (const line of lines.slice(0, 50)) {
    if (line.startsWith('/*')) comment = true;
    if (/^; Listing generated by Microsoft/.test(line) ||
        /^(?:(?:CONST|_BSS|_DATA|_TEXT)\s+SEGMENT(?!\w))|\s*\.[2-6]86P?(?!\w)|\s*\.XMM(?!\w)/i.test(line)) return null;
    if (line.includes('Texas Instruments Incorporated') || (line.startsWith('*') && !comment)) return null;
    if (/\.(?:title|ident|macro|subtitle|library)(?!\w)/i.test(line)) return null;
  }
  return 'asm';
}

// ".i": Assembler oder Progress (SWIG hat keine Regeln)
function dotI(lines) {
  for (let i = 0; i < 50 && i < lines.length - 1; i++) {
    if (/^\s*;|^\*/.test(lines[i])) return assembler(lines);
    if (/^\s*%(?:\{|(?:addmethods|apply|beginfile|clear|constant|define|echo|enddef|endoffile|extend|feature|fragment|ignore|import|importfile|include|includefile|inline|insert|keyword|module|name|namewarn|native|newobject|parms|pragma|rename|template|typedef|typemap|types|varargs|warn))/.test(lines[i])) return null;
  }
  return 'progress';
}

function dotR(lines) {
  if (any(lines, 50, /(?<!\w)REBOL(?!\w)/i)) return null;
  for (const line of lines.slice(0, 50)) {
    if (/^\s*#/.test(line)) return 'r';
    if (/^\s*\/\*/.test(line)) return null; // Rexx
  }
  return 'r';
}

// ".d": D oder DTrace
function dotD(lines) {
  if (any(lines, 100, /^(?:module|import)(?!\w)/)) return 'd';
  return any(lines, 100, /^#!\S+dtrace|#pragma\s+D\s+option|:\S*?:\S*?:/) ? null : 'd';
}

// ".cls": LaTeX, Smalltalk oder Visual Basic (Rexx, ObjectScript haben keine Regeln)
function dotCls(lines) {
  if (/^#!.*(?<!\w)(?:rexx|regina)(?!\w)/.test(lines[0])) return null;
  if (lines[0] === 'VERSION 1.0 CLASS') return 'vb';
  const line = lines.find((l) => /\S/.test(l) && !/^\s*(?:import|include|includegenerator)(?!\w)/i.test(l)) ?? '';
  if (/^\s*class(?!\w)\s+[%a-z][%a-z0-9_.]*(?:\s+extends(?!\w)|\s*\[|\s*\{|$)/i.test(line)) return null;
  if (/^[%\\]/.test(line)) return 'tex';
  return /^\s*(?:\/\*|::\w)/.test(line) ? null : 'st';
}

// ".sh": andere Shells haben eigene oder keine Regeln. Eine Zeile "exec wish" macht Tcl daraus
function dotSh(lines) {
  if (/^#!.{2,}?(?<!\w)(?:csh|tcsh|zsh)(?!\w)/.test(lines[0])) return null;
  let n = 1;
  while (n < 19 && n < lines.length - 1 && /^\s*(?:#|$)/.test(lines[n])) n++;
  if (n < lines.length - 1 && /\s*exec\s/.test(lines[n]) && /^\s*#.*\\$/.test(lines[n - 1]) &&
      /(?<!\w)(?:tclsh|wish)/.test(lines[n].replace(/\s*exec\s+(?:[^ ]*\/)?/, ''))) return 'tcl';
  return 'sh';
}

function dotCmd(lines) {
  if (/MEMORY|SECTIONS|(?:^|\n)--\S|(?:^|\n)\/\//.test(lines.slice(0, 20).join('\n'))) return null;
  return lines[0].startsWith('/*') ? null : 'dosbatch';
}

// ".xml": DocBook und XBL sind in Vim eigene Typen
function docbook(lines) {
  for (const line of lines.slice(0, 99)) {
    if (/<!DOCTYPE.*DocBook| xmlns="http:\/\/docbook\.org\/ns\/docbook"|xmlns:xbl="http:\/\/www\.mozilla\.org\/xbl"/.test(line)) return null;
  }
  return 'xml';
}

// ".tex": Wie FTtex in Vim. Die erste Zeile "%&..." nennt das Format, sonst entscheiden die
// Befehle ab der ersten Zeile, die kein Kommentar ist; ohne Hinweis ist es Plain TeX.
// ConTeXt hat keine Regeln.
const LATEX = /^\s*\\(?:(?:documentclass|usepackage|newcommand|renewcommand)(?![A-Za-z0-9_À-ÿ])|begin\{)/;
const CONTEXT = /^\s*\\(start[a-zA-Z]+|setup[a-zA-Z]+|usemodule|enablemode|enableregime|setvariables|useencoding|usesymbols|stelle[a-zA-Z]+|verwende[a-zA-Z]+|stel[a-zA-Z]+|gebruik[a-zA-Z]+|usa[a-zA-Z]+|imposta[a-zA-Z]+|regle[a-zA-Z]+|utilisemodule(?![A-Za-z0-9_À-ÿ]))/;
function dotTex(lines, fileName) {
  const named = /^%&\s*([a-zA-Z]+)/.exec(lines[0]);
  if (named) {
    const format = named[1].toLowerCase().replace('pdf', '');
    if (format === 'context') return null;
    return format === 'plain' || format === 'plaintex' ? 'plaintex' : 'tex';
  }
  if (/tex\/context\/.*\/.*.tex/.test(fileName)) return null;
  const first = lines.slice(0, 1000).findIndex((line) => /^\s*[^\s%]/.test(line));
  if (first < 0) return 'plaintex';
  for (const line of lines.slice(first, first + 1001)) {
    if (LATEX.test(line)) return 'tex';
    if (CONTEXT.test(line)) return null;
  }
  return 'plaintex';
}

