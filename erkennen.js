// Dateien ohne Endung und ohne "#!": XML und Diff erkennt Vim an den ersten Zeilen
function plain(lines) {
  const [one = '', two = '', three = '', four = ''] = lines;
  if (/^(?:diff(?![A-Za-z0-9_])|Only in |\d+(?:,\d+)?[cda]\d+(?:,\d+)?$|# It was generated by makepatch |Index:\s+\S+$|===== \S+ \d+\.\d+ vs edited|==== \/\/\S+#\d+|# HG changeset patch)/.test(one) ||
      (/^--- /.test(one) && /^\+\+\+ /.test(two)) || (/^\* looking for /.test(one) && /^\* comparing to /.test(two)) ||
      (/^\*\*\* /.test(one) && /^--- /.test(two)) ||
      (/^=== /.test(one) && ((/^={66}/.test(two) && /^--- /.test(three) && /^\+\+\+/.test(four)) || (/^--- /.test(two) && /^\+\+\+ /.test(three)))) ||
      /^=== (?:removed|added|renamed|modified)/.test(one)) return 'diff';
  return /<\?\s*xml.*?>/.test(one) ? 'xml' : null;
}

function shebang(lines) {
  let line = lines[0];
  if (!line.startsWith('#!')) return null;
  // "#!/usr/bin/env -S programm" wie "#!/usr/bin/programm"
  if (/^#!\s*\S*(?<!\w)env\s/.test(line)) {
    line = line.replace(/(\s)--split-string[ \t=]/, '$1')
      .replace(/(\s)[A-Za-z0-9_]+=\S*(?=\s)/g, '$1')
      .replace(/(\s)(?:-[iS]+|--ignore-environment)(?=\s)/g, '$1')
      .replace(/(?<!\w)env\s+/, '');
  }
  const words = line.slice(2).trim().split(/\s+/);
  let name = words[0].split(/[/\\]/).pop();
  if (name === 'env' || name === 'busybox') name = words[1] ?? '';
  if (/^exec wish/.test(lines[2] ?? '')) name = 'wish';
  const found = PROGRAMS.find(([pattern]) => pattern.test(name));
  return found ? found[1] : null;
}

// ---- Welche Shell? ---------------------------------------------------------------

const BASH_NAMES = /^(?:\.bashrc.*|bashrc|bash\.bashrc|\.bash[_-](?:profile|logout|aliases).*|\.bash[_-]history|bash-fc[-.].*|PKGBUILD.*|APKBUILD.*|.*\.(?:ebuild|bash|eclass|bats|cygport|install))$/;
const KSH_NAMES = /^\.kshrc.*$|\.ksh$/;

// Wie sh.vim: Die erste Zeile entscheidet, sonst der Dateiname. Sonst gilt, was /bin/sh
// ist: unter Windows und mit dash eine POSIX-Shell
function shell(base, line) {
  if (/^#!.{2,}?(?<!\w)(?:ksh(?:93u+|93v|93|2020|88)?|mksh)(?!\w)/.test(line)) return 'sh-ksh';
  if (/^#!.{2,}?(?<!\w)bash(?!\w)/.test(line)) return 'sh';
  if (/^#!.{2,}?(?<!\w)dash(?!\w)/.test(line)) return 'sh-posix';
  if (KSH_NAMES.test(base)) return 'sh-ksh';
  return BASH_NAMES.test(base) ? 'sh' : 'sh-posix';
}

